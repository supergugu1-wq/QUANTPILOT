-- QuantPilot V7: risk limits, emergency stop, health/audit events
alter table public.bot_configs add column if not exists max_order_usd numeric not null default 500;
alter table public.bot_configs add column if not exists max_exposure_usd numeric not null default 2000;
alter table public.bot_configs add column if not exists max_trades_day integer not null default 5;
alter table public.bot_configs add column if not exists kill_switch boolean not null default false;
create table if not exists public.risk_events (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 event_type text not null, severity text not null default 'info', details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.risk_events enable row level security;
drop policy if exists "risk own select" on public.risk_events;
create policy "risk own select" on public.risk_events for select using (auth.uid()=user_id);
create index if not exists risk_events_user_created_idx on public.risk_events(user_id,created_at desc);
