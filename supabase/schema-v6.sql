-- QuantPilot V6: conexão individual com corretora; nenhum saldo/dinheiro é custodiado pelo QuantPilot.
create table if not exists public.broker_connections (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 provider text not null check(provider in ('alpaca')),
 environment text not null default 'paper' check(environment in ('paper','live')),
 access_token_enc text not null,
 broker_account_id text,
 scope text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(user_id,provider)
);
alter table public.broker_connections enable row level security;
-- Intencionalmente sem policies para usuários: tokens só são acessados pelo backend com service role.
create index if not exists broker_connections_user on public.broker_connections(user_id);
